export const opcUaTagTypes = Object.freeze([
  ['BIT', 'BIT — Boolean'],
  ['BYTE', 'BYTE — 8-bit bit string'],
  ['SINT', 'SINT — signed 8-bit'], ['USINT', 'USINT — unsigned 8-bit'],
  ['WORD', 'WORD — 16-bit bit string'],
  ['INT', 'INT — signed 16-bit'], ['UINT', 'UINT — unsigned 16-bit'],
  ['DWORD', 'DWORD — 32-bit bit string'],
  ['DINT', 'DINT — signed 32-bit'], ['UDINT', 'UDINT — unsigned 32-bit'],
  ['LWORD', 'LWORD — 64-bit bit string'],
  ['LINT', 'LINT — signed 64-bit'], ['ULINT', 'ULINT — unsigned 64-bit'],
]);
export function opcUaTagTypeLabel(type) {
  return opcUaTagTypes.find(([value]) => value === type)?.[1] || type;
}
export function formatOpcUaTagAddress(tag) {
  const bit = ['M', 'P', 'K', 'L'].includes(tag.addressArea);
  return tag.addressArea + (bit
    ? String(Math.floor(tag.addressNumber / 16)).padStart(4, '0') + (tag.addressNumber % 16).toString(16).toUpperCase()
    : String(tag.addressNumber).padStart(tag.addressArea === 'D' ? 6 : 5, '0'));
}
export function parseOpcUaTagAddress(text) {
  const match = /^([PMKLD])([0-9A-F]+)$/.exec(text.trim().toUpperCase());
  if (!match) throw new Error('Enter a P, M, K, L or D device address.');
  const [, addressArea, body] = match;
  const bit = addressArea !== 'D';
  if (bit && !/^\d+[0-9A-F]$/.test(body)) throw new Error('A bit device uses a decimal word number followed by a hexadecimal bit (0–F), such as M0000A.');
  if (!bit && !/^\d+$/.test(body)) throw new Error('Enter a decimal device number.');
  const addressNumber = bit ? Number(body.slice(0, -1)) * 16 + parseInt(body.slice(-1), 16) : Number(body);
  if (!Number.isSafeInteger(addressNumber)) throw new Error('Device number is too large.');
  return {addressArea, addressNumber};
}
export function renderOpcUaTags({host, table, element, property, button, validatePatch, commit}) {
  const section = element('section', 'opcua-tags');
  section.append(element('h3', '', 'OPC UA nodes'));
  section.append(element('p', 'module-selection-note', 'Exported PLC tags are shared by EtherNet/IP and OPC UA. Node IDs are generated by the server.'));
  if (table.error) { section.append(element('p', 'module-selection-error', table.error)); host.append(section); return; }
  const tags = table.tags;
  const list = element('div', 'opcua-tag-list');
  const panel = element('div', 'opcua-tag-editor');
  const renderForm = index => {
    panel.replaceChildren();
    const selected = index == null ? null : tags[index];
    panel.append(element('h4', '', selected ? `Edit ${selected.name}` : 'New node'));
    const name = property(panel, 'Node name', selected?.name || '', false); name.setAttribute('aria-label', 'Node name');
    const typeRow = element('label', 'property-field'); typeRow.append(element('span', 'property-label', 'Data type'));
    const type = document.createElement('select'); type.setAttribute('aria-label', 'Node data type');
    const types = opcUaTagTypes.map(([value]) => value);
    if (selected && !types.includes(selected.dataType)) types.push(selected.dataType);
    types.forEach(value => { const option = element('option', '', opcUaTagTypeLabel(value)); option.value = value; type.append(option); });
    type.value = selected?.dataType || 'WORD'; typeRow.append(type); panel.append(typeRow);
    const address = property(panel, 'Device', selected ? formatOpcUaTagAddress(selected) : 'D000000', false); address.setAttribute('aria-label', 'Node device');
    const comment = property(panel, 'Description', selected?.comment || '', false, true); comment.setAttribute('aria-label', 'Node description');
    const error = element('p', 'module-selection-error', ''); error.setAttribute('role', 'alert');
    const patch = () => ({configurationIndex: table.configurationIndex, expectedTags: tags, index, tag: {
      name: name.value, dataType: type.value, ...parseOpcUaTagAddress(address.value, type.value), comment: comment.value,
    }});
    const save = button(selected ? 'Apply node changes' : 'Add node', 'primary-button', () => commit(patch()));
    save.textContent = selected ? 'Apply node changes' : 'Add node';
    const validate = () => {
      try {
        const update = patch();
        if (selected && JSON.stringify(update.tag) === JSON.stringify(selected)) { save.disabled = true; error.textContent = ''; return; }
        validatePatch(update); error.textContent = ''; save.disabled = false;
      } catch (e) { save.disabled = true; error.textContent = String(e); }
    };
    for (const input of [name, type, address, comment]) { input.addEventListener('input', validate); input.addEventListener('change', validate); }
    panel.append(error, save);
    if (selected) {
      const remove = button(`Delete ${selected.name}`, 'secondary-button', () => commit({configurationIndex: table.configurationIndex, expectedTags: tags, index, tag: null}));
      remove.textContent = 'Delete node'; panel.append(remove);
    }
    save.disabled = true;
  };
  if (tags.length) {
    for (const [index, tag] of tags.entries()) {
      const row = button(`Edit node ${tag.name}`, 'secondary-button', () => renderForm(index));
      row.textContent = `${tag.name} · ${opcUaTagTypeLabel(tag.dataType)} · ${formatOpcUaTagAddress(tag)}`;
      list.append(row);
    }
  } else list.append(element('p', 'module-selection-note', 'No exported nodes.'));
  const add = button('New OPC UA node', 'secondary-button', () => renderForm(null)); add.textContent = 'New node';
  section.append(list, add, panel); host.append(section);
  renderForm(tags.length ? 0 : null);
}
